const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('eligibility.html','utf8'),attrs=new Map(),label={textContent:''};
const status={hidden:true},elapsed={firstChild:{nodeValue:'0:00'}};
const bar={hidden:true,style:{setProperty(){}},classList:{toggle(){}},setAttribute:(name,value)=>attrs.set(name,value),querySelector:()=>label};
const elements={'criteria-working':status,'criteria-elapsed':elapsed,'criteria-progress':bar};
let tick=null,time=1000;
const ctx={$:id=>elements[id],Date:{now:()=>time},setTimeout:fn=>{tick=fn;return 1},clearTimeout:()=>{tick=null}};
vm.createContext(ctx);vm.runInContext(html.slice(html.indexOf('let generationController=null'),html.indexOf('\nfunction setMachineStatus')),ctx);
assert(html.indexOf('id="criteria-progress"')<html.indexOf('id="criteria-working"')&&html.indexOf('id="criteria-working"')<html.indexOf('id="preview"'));
ctx.criteriaWaiting(true);ctx.criteriaProgress(15);assert.equal(status.hidden,false);
time+=12000;tick();assert.equal(elapsed.firstChild.nodeValue,'0:12');
assert.equal(attrs.get('aria-valuenow'),'15');assert.equal(label.textContent,'15%');
ctx.criteriaWaiting(true);ctx.criteriaProgress(60);time+=5000;tick();
assert.equal(elapsed.firstChild.nodeValue,'0:17');assert.equal(label.textContent,'60%');
ctx.criteriaProgress(100);ctx.criteriaWaiting(false);assert.equal(status.hidden,true);assert.equal(tick,null);assert.equal(label.textContent,'100%');
ctx.criteriaWaiting(true);assert.equal(elapsed.firstChild.nodeValue,'0:00');ctx.criteriaWaiting(false);assert.equal(tick,null);
console.log('PASS: stage percentage and elapsed time appear separately, the clock spans retries and stages, and restarts from zero on a new run.');
