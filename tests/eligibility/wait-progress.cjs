const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('eligibility.html','utf8');
const status={hidden:true},elapsed={textContent:'0:00'},working={hidden:false},finished={hidden:true};
const elements={'criteria-timing':status,'criteria-elapsed':elapsed,'criteria-working-label':working,'criteria-finished-label':finished,
 'generation-method':{value:'machine'},question:{value:'Exercise in adults'}};
let tick=null,time=1000;
const state={reviewType:'Systematic Review',machineRun:null};
const ctx={state,$:id=>elements[id],Date:{now:()=>time},setTimeout:fn=>{tick=fn;return 1},clearTimeout:()=>{tick=null}};
vm.createContext(ctx);vm.runInContext(html.slice(html.indexOf('let generationController=null'),html.indexOf('\nfunction setMachineStatus')),ctx);
assert(!html.includes('role="progressbar"'));
assert(html.indexOf('id="criteria-timing"')<html.indexOf('id="preview"'));
ctx.renderCriteriaTiming();assert(status.hidden);
ctx.startCriteriaTiming();assert(!status.hidden&&!working.hidden&&finished.hidden);
time+=12000;tick();assert.equal(elapsed.textContent,'0:12');
state.machineRun={question:elements.question.value,reviewType:state.reviewType,elapsedMs:17500};
ctx.stopCriteriaTiming();assert(!status.hidden&&working.hidden&&!finished.hidden);assert.equal(tick,null);
assert.equal(elapsed.textContent,'0:17');
time+=5000;ctx.renderCriteriaTiming();assert.equal(elapsed.textContent,'0:17');
ctx.startCriteriaTiming();assert.equal(elapsed.textContent,'0:00');
ctx.stopCriteriaTiming();assert.equal(elapsed.textContent,'0:17');
state.machineRun=null;ctx.renderCriteriaTiming();assert(status.hidden);
console.log('PASS: the timer freezes after completion, retains the last successful duration on cancellation and clears with the criteria.');
